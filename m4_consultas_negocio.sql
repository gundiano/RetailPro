---------- RESUMEN EJECUTIVO MENSUAL--------------

SELECT
SUM(Cantidad * Precio_unitario) AS TOTAL_FACTURADO,
COUNT(Id_Venta) AS CANTIDAD_PEDIDOS,
AVG(Cantidad * Precio_unitario) AS PROMEDIO_TICKET
FROM Ventas
GROUP BY MONTH(Fecha_Venta);


----------- RANKING DE PRODUCTOS -------------

SELECT TOP 5 id_producto,
SUM (Cantidad) AS TOTAL_UNIDADES_VENDIDAS,
SUM (Cantidad * Precio_unitario) AS TOTAL_FACTURADO
FROM Ventas
GROUP BY (Id_Producto)
ORDER BY (TOTAL_FACTURADO) DESC;

------------ CLIENTES RECURRENTES ------------

SELECT id_cliente,
COUNT (id_venta) AS PEDIDOS,
SUM (Cantidad * Precio_unitario) AS TOTAL_GASTADO
FROM Ventas
GROUP BY (id_cliente)
HAVING COUNT (*) > 1
ORDER BY (TOTAL_GASTADO) DESC;



---------- MESES POR ENCIMA/MESES POR DEBAJO DEL PROMEDIO-----

SELECT MES,
TOTAL_FACTURADO_MES,
CASE WHEN TOTAL_FACTURADO_MES > PROMEDIO_TOTAL_FACTURADO
THEN 'POR ENCIMA'
ELSE 'POR DEBAJO'
END AS 'POR ENCIMA/POR DEBAJO'
FROM (SELECT MONTH (Fecha_venta) AS MES,
SUM(Cantidad*Precio_unitario) AS TOTAL_FACTURADO_MES,
AVG (Cantidad*Precio_unitario) AS PROMEDIO_TOTAL_FACTURADO
FROM Ventas
GROUP BY YEAR(Fecha_venta),MONTH (Fecha_venta)) t;




